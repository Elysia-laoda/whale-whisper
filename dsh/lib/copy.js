/**
 * 「关掉挂件」意图识别。与参考实现同一套正则：允许中间夹少量任意字符，
 * 覆盖「关掉挂件」「挂件关掉吧」「不需要悬浮窗了」这类说法。
 */
export const DISMISS_RE = new RegExp(
  [
    '(关|关闭|关掉|收起|收掉|撤掉|不用|不要|不需要|别开|别在|别再)[^，。！？,.]{0,8}(挂件|悬浮窗|小鲸鱼|whale)',
    '(挂件|悬浮窗|小鲸鱼|whale)[^，。！？,.]{0,8}(关掉|关闭|收起|收掉|撤掉|不用了|不要了|不需要了|别开了)',
  ].join('|'),
  'i',
);

/**
 * 这段文本是否表达了「关掉挂件」。
 * @param text - 任意文本（通常是用户本轮发言的拼接结果）。
 * @returns 命中返回 true。
 */
export function isDismissIntent(text) {
  if (typeof text !== 'string' || text.length === 0) return false;
  return DISMISS_RE.test(text);
}
